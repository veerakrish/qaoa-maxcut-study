"""Apply the decision rules of docs/PREREGISTRATION.md to results/raw and write tables and figures."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from .experiment import Config


def load(raw_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    runs, base = [], []
    for f in sorted(raw_dir.glob("*.json")):
        d = json.loads(f.read_text())
        for r in d["runs"]:
            runs.append({"n": d["n"], "instance": d["instance"], **{k: v for k, v in r.items() if k != "params"}})
        base.append({"n": d["n"], "instance": d["instance"], **d["baselines"]})
    return pd.DataFrame(runs), pd.DataFrame(base)


def boot(values, B: int = 10_000, seed: int = 0) -> tuple[float, float, float]:
    """Mean and 95% percentile-bootstrap interval of the mean over graphs."""
    v = np.asarray(values, dtype=float)
    means = v[np.random.default_rng(seed).integers(0, len(v), (B, len(v)))].mean(axis=1)
    return float(v.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def fmt(t: tuple[float, float, float], digits: int = 3) -> str:
    return f"{t[0]:.{digits}f} [{t[1]:.{digits}f}, {t[2]:.{digits}f}]"


def md_table(rows: list[dict]) -> str:
    cols = list(rows[0])
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(lines)


def per_instance(runs: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    ideal = runs[runs["mode"] == "ideal"]
    keys = ["n", "instance", "p"]
    agg = ideal.groupby(keys).agg(r_best=("ratio", "max"), r_mean=("ratio", "mean"), nfev=("nfev", "mean")).reset_index()
    best = ideal.loc[ideal.groupby(keys)["ratio"].idxmax(), keys + ["p_optimal", "best_of_S_ratio"]]
    ideal_inst = agg.merge(best, on=keys)
    shots = runs[runs["mode"] == "shots"]
    shots_inst = shots.groupby(keys).agg(r_mean=("ratio", "mean"), nfev=("nfev", "mean"),
                                         shots_used=("shots_used", "mean")).reset_index()
    return ideal_inst, shots_inst


def analyse(raw_dir: Path, out_dir: Path, fig_dir: Path) -> None:
    cfg = Config(**{k: tuple(v) if isinstance(v, list) else v
                    for k, v in json.loads((raw_dir.parent / "config.json").read_text()).items()})
    runs, base = load(raw_dir)
    ideal, shots = per_instance(runs)
    sizes, depths = list(cfg.sizes), list(cfg.depths)
    out: list[str] = []

    # ---- validation gates ------------------------------------------------------------------------------------------
    gates = []
    gates.append(("no run has ratio > 1 + 1e-9", bool((runs["ratio"] <= 1 + 1e-9).all())))
    per_graph = runs.groupby(["n", "instance"]).size()
    gates.append((f"every graph has {len(depths) * cfg.restarts * 2} runs", bool((per_graph == len(depths) * cfg.restarts * 2).all())))
    counts = base.groupby("n").size().to_dict()
    gates.append(("graph counts per size: " + ", ".join(f"n={n}: {counts.get(n, 0)}" for n in sizes), True))
    gates.append(("SDP value >= exact maximum cut on every graph", bool((base["sdp_value"] >= base["cmax"] - 1e-6).all())))
    out += ["# Results", "", f"Generated by `python -m qaoa_study.analysis` from `results/raw` ({len(base)} graphs, {len(runs)} optimisation runs). "
            "Interpretation follows the decision rules in `docs/PREREGISTRATION.md`; intervals are 95% bootstrap over graphs.", "",
            "## Validation gates", ""] + [f"- {'PASS' if ok else 'FAIL'}: {name}" for name, ok in gates] + [""]

    # ---- main table -------------------------------------------------------------------------------------------------
    rows, summary_csv = [], []
    for n in sizes:
        for p in depths:
            i = ideal[(ideal.n == n) & (ideal.p == p)]
            s = shots[(shots.n == n) & (shots.p == p)]
            enh = (i["p_optimal"].values / base[base.n == n].sort_values("instance")["uniform_p_optimal"].values)
            row = {"n": n, "p": p, "graphs": len(i), "ideal r_best": fmt(boot(i.r_best)), "ideal r_mean": fmt(boot(i.r_mean)),
                   "shots r_mean": fmt(boot(s.r_mean)), "evals ideal": f"{i.nfev.mean():.0f}", "evals shots": f"{s.nfev.mean():.0f}",
                   "P(opt) gain over uniform (median)": f"{np.median(enh):.1f}x"}
            rows.append(row)
            summary_csv.append({"n": n, "p": p, "graphs": len(i), "ideal_r_best": i.r_best.mean(), "ideal_r_mean": i.r_mean.mean(),
                                "shots_r_mean": s.r_mean.mean(), "evals_ideal": i.nfev.mean(), "evals_shots": s.nfev.mean(),
                                "median_p_opt_gain": float(np.median(enh))})
    out += ["## Approximation ratio <C> / C_max by size and depth", "", md_table(rows), "",
            "`r_best`: best of 5 restarts by exact <C>; `r_mean`: mean over restarts. 'shots' arm: 1024 shots per evaluation, summarised by `r_mean` only.", ""]
    pd.DataFrame(summary_csv).to_csv(out_dir / "summary.csv", index=False)

    brow = []
    for n in sizes:
        b = base[base.n == n]
        brow.append({"n": n, "graphs": len(b), "random cut": fmt(boot(b.random_ratio)), "GW single rounding": fmt(boot(b.gw_single_ratio)),
                     "local search single run": fmt(boot(b.ls_single_ratio)), "local search best of 10": fmt(boot(b.ls_best_of_10_ratio)),
                     "GW best of 1024": fmt(boot(b.gw_best_of_S_ratio)), "uniform best of 1024": fmt(boot(b.random_best_of_S_ratio))})
    out += ["## Classical baselines (same ratio)", "", md_table(brow), ""]

    # ---- H1 ----------------------------------------------------------------------------------------------------------
    def wide(df, col):
        return df.pivot(index=["n", "instance"], columns="p", values=col)

    h1_rows, h1_ok = [], True
    for col in ("r_best", "r_mean"):
        w = wide(ideal, col)
        for n in sizes:
            wn = w.loc[n]
            for p0, p1 in zip(depths[:-1], depths[1:]):
                t = boot((wn[p1] - wn[p0]).values)
                ok = t[1] > 0
                if col == "r_best":
                    h1_ok &= ok
                h1_rows.append({"metric": col, "n": n, "step": f"p={p0}->{p1}", "mean difference [95% CI]": fmt(t, 4), "interval above 0": "yes" if ok else "NO"})
    out += ["## H1: does depth help? (ideal arm)", "", f"**Verdict on `r_best`: {'SUPPORTED' if h1_ok else 'NOT SUPPORTED at every size and step'}**", "", md_table(h1_rows), ""]

    # ---- H2 ----------------------------------------------------------------------------------------------------------
    pmax = depths[-1]
    h2_rows, h2_below = [], True
    base_i = base.set_index(["n", "instance"])
    for col in ("r_best", "r_mean"):
        w = wide(ideal, col)[pmax]
        for n in sizes:
            for name, bcol in (("GW single rounding", "gw_single_ratio"), ("local search single run", "ls_single_ratio")):
                d = (w.loc[n] - base_i.loc[n][bcol]).values
                t = boot(d)
                below = t[2] < 0
                h2_below &= below
                h2_rows.append({"metric": col, "n": n, "baseline": name, f"QAOA p={pmax} minus baseline [95% CI]": fmt(t, 4), "QAOA below": "yes" if below else "NO"})
    out += [f"## H2: QAOA p={pmax} against single-run classical baselines", "",
            f"**Verdict: QAOA {'is below both baselines at every size' if h2_below else 'is NOT below both baselines at every size; see rows marked NO (check for a bug first, per the pre-registration)'}**", "",
            md_table(h2_rows), ""]

    # ---- H3 ----------------------------------------------------------------------------------------------------------
    h3_rows, h3_below = [], True
    wi, ws = wide(ideal, "r_mean"), wide(shots, "r_mean")
    for n in sizes:
        for p in depths:
            d = (ws.loc[n][p] - wi.loc[n][p]).values
            t = boot(d)
            below = t[2] < 0
            h3_below &= below
            s = shots[(shots.n == n) & (shots.p == p)]
            i = ideal[(ideal.n == n) & (ideal.p == p)]
            h3_rows.append({"n": n, "p": p, "shots minus ideal r_mean [95% CI]": fmt(t, 4), "below": "yes" if below else "NO",
                            "evals shots / ideal": f"{s.nfev.mean():.0f} / {i.nfev.mean():.0f}", "shots used": f"{s.shots_used.mean():,.0f}"})
    out += ["## H3: does shot noise cost solution quality? (mean over restarts)", "",
            f"**Verdict: the shots arm is {'below the ideal arm at every (n, p)' if h3_below else 'NOT below the ideal arm at every (n, p); see rows marked NO'}.** "
            "Shot noise and COBYLA's earlier stopping are confounded (see evaluations).", "", md_table(h3_rows), ""]

    # ---- H4 ----------------------------------------------------------------------------------------------------------
    h4_rows = []
    for n in sizes:
        i = ideal[(ideal.n == n) & (ideal.p == pmax)].sort_values("instance")
        b = base[base.n == n].sort_values("instance")
        h4_rows.append({"n": n, "uniform P(opt)": f"{b.uniform_p_optimal.mean():.4f}", f"QAOA p={pmax} P(opt)": f"{i.p_optimal.mean():.4f}",
                        "median gain": f"{np.median(i.p_optimal.values / b.uniform_p_optimal.values):.1f}x",
                        f"QAOA best of 1024 shots": fmt(boot(i.best_of_S_ratio)), "uniform best of 1024": fmt(boot(b.random_best_of_S_ratio)),
                        "GW best of 1024": fmt(boot(b.gw_best_of_S_ratio))})
    out += ["## H4 (descriptive): success probability and best-of-shots", "", md_table(h4_rows), ""]

    (out_dir / "summary.md").write_text("\n".join(out), encoding="utf-8")

    # ---- figures -----------------------------------------------------------------------------------------------------
    fig, axes = plt.subplots(1, len(sizes), figsize=(4 * len(sizes), 3.8), sharey=True)
    for ax, n in zip(np.atleast_1d(axes), sizes):
        b = base[base.n == n]
        for label, df, col, style in (("QAOA ideal, best of 5", ideal, "r_best", "o-"), ("QAOA ideal, mean of 5", ideal, "r_mean", "s--"),
                                      ("QAOA shots (1024/eval), mean of 5", shots, "r_mean", "^:")):
            m = np.array([boot(df[(df.n == n) & (df.p == p)][col]) for p in depths])
            ax.plot(depths, m[:, 0], style, label=label)
            ax.fill_between(depths, m[:, 1], m[:, 2], alpha=0.15)
        for label, col, ls in (("Goemans-Williamson (single rounding)", "gw_single_ratio", "-."), ("local search (single run)", "ls_single_ratio", "-"),
                               ("random cut", "random_ratio", ":")):
            ax.axhline(b[col].mean(), color="gray", linestyle=ls, linewidth=1, label=label)
        ax.set(title=f"n = {n} ({len(b)} graphs)", xlabel="QAOA depth p", xticks=depths)
    np.atleast_1d(axes)[0].set_ylabel("approximation ratio <C> / C_max")
    np.atleast_1d(axes)[-1].legend(fontsize=7, loc="lower right")
    fig.tight_layout()
    fig.savefig(fig_dir / "ratio_vs_p.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(5, 3.8))
    for n in sizes:
        gains = [np.median(ideal[(ideal.n == n) & (ideal.p == p)].sort_values("instance").p_optimal.values
                           / base[base.n == n].sort_values("instance").uniform_p_optimal.values) for p in depths]
        ax.plot(depths, gains, "o-", label=f"n = {n}")
    ax.set(xlabel="QAOA depth p", ylabel="P(optimal cut) / uniform (median)", yscale="log", xticks=depths)
    ax.legend()
    fig.tight_layout()
    fig.savefig(fig_dir / "p_optimal_gain.png", dpi=160)
    plt.close(fig)
    print("\n".join(out[:12]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--raw", default="results/raw")
    ap.add_argument("--out", default="results")
    ap.add_argument("--figures", default="figures")
    a = ap.parse_args(argv)
    Path(a.out).mkdir(exist_ok=True)
    Path(a.figures).mkdir(exist_ok=True)
    analyse(Path(a.raw), Path(a.out), Path(a.figures))


if __name__ == "__main__":
    main()
